"""Pins the door-flip contract of ``bim.toggle_door_swing`` (#8399).

Three legs:

* ``is_external_door`` — the pure decision feeding the confirmation gate.
  External doors are factory-handed: the flipped door is a different product,
  so the swing-arc click must ask before applying.
* invoke wiring — external doors route through ``invoke_confirm``; internal
  doors flip straight away; Shift is captured before the dialog.
* OperationType sync — finishing a hand flip on an occurrence whose
  ``BBIM_Door`` pset lives on its IfcDoorType must update the type's
  ``OperationType`` too (the type's pset and mapped geometry are already
  regenerated by the edit, so a stale type attribute would contradict both).
"""

