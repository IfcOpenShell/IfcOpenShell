import bpy
import pytest

import bonsai.tool as tool
from test.bim.bootstrap import NewFile


class TestRotate90(NewFile):
    def test_rotating_a_structural_curve_member(self):
        # An IfcStructuralItem is not an IfcElement, and has no ConnectedTo or ConnectedFrom.
        bpy.ops.bim.create_project()
        props = tool.Root.get_root_props()
        props.ifc_product, props.ifc_class, props.representation_template = (
            "IfcStructuralItem",
            "IfcStructuralCurveMember",
            "EDGE",
        )
        bpy.ops.bim.add_element(skip_dialog=True)
        member = tool.Ifc.get().by_type("IfcStructuralCurveMember")[0]
        obj = tool.Ifc.get_object(member)
        with bpy.context.temp_override(selected_objects=[obj], active_object=obj):
            bpy.ops.bim.rotate_90(axis="Z")
        assert obj.rotation_euler.to_matrix().col[0].to_3d().y == pytest.approx(1.0)
